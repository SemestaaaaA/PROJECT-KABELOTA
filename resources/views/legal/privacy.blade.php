    <li>Menghubungkan talenta dan perusahaan lewat tawaran rekrut dan lamaran.</li>
    <li>Memverifikasi legalitas perusahaan dan pembayaran lowongan.</li>
    <li>Mengirim email terkait akun, tawaran, dan lamaran.</li>
    <li>Menyusun statistik agregat yang tidak mengidentifikasi orang per orang.</li>
</ul>
<p>Dasar pemrosesannya adalah persetujuan yang Anda berikan saat mendaftar dan membuat profil, serta pelaksanaan layanan yang Anda minta.</p>

